#!/usr/bin/env python3
"""The games Mudlet's connection dialog offers, for the app's profile list, from Mudlet's src/TGameDetails.h, and
Mudlet's Lua functions, for the Lua editor's completions, from its src/lua-function-list.json.

Writes app/src/main/assets/games/games.json (each game's name, address, links and description, and the Mudlet commit
they come from) and each game's logo, scaled down, as app/src/main/assets/games/icons/<name>.webp. Mudlet Web's
scripts/sync-mudlet-games.mjs reads the same header the same way. Writes app/src/main/assets/lua/functions.json too:
each function's name with how it is called, as Mudlet's list has them, from the same commit.

    scripts/sync-mudlet-games.py ../mudlet            # resync from a Mudlet checkout, at the commit it has out
    scripts/sync-mudlet-games.py --check              # CI: the committed list is what Mudlet at its commit gives
    scripts/sync-mudlet-games.py --check ../mudlet    # the same, against a checkout instead of GitHub

Writing needs Pillow (for the logos) and git (for the checkout's commit); --check needs neither, only the network
when no checkout is given: it reads the header, mudlet.qrc and the logos from GitHub at the commit games.json names,
so a game Mudlet adds later does not fail it. Resync to take Mudlet's newer list.
"""

import argparse
import hashlib
import io
import json
import re
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "app/src/main/assets/games"
OUT_JSON = OUT_DIR / "games.json"
ICON_DIR = OUT_DIR / "icons"
LUA_JSON = ROOT / "app/src/main/assets/lua/functions.json"
RAW = "https://raw.githubusercontent.com/Mudlet/Mudlet/{commit}/src/{path}"

# The list draws a logo at 96 x 24 dp and a game's details at twice that. Most of Mudlet's logos are 120 x 30 or
# 240 x 60; the few at 480 x 120 would only add to the APK at full size.
ICON_MAX = (240, 60)
ICON_QUALITY = 90

# Not offered on Android: the tutorial is a package Mudlet plays for a profile of this name at localhost, port 0,
# which the engine's profiles cannot hold (docs/divergences.md, "The games the profile list offers")
LEFT_OUT = {"Mudlet Tutorial"}

COMMENT = (
    "GENERATED by scripts/sync-mudlet-games.py from Mudlet's src/TGameDetails.h at mudletCommit; do not edit. "
    "The games the profile list offers, as Mudlet's connection dialog does; icons/ has their logos."
)

LUA_COMMENT = (
    "GENERATED by scripts/sync-mudlet-games.py from Mudlet's src/lua-function-list.json at mudletCommit; do not edit. "
    "Mudlet's Lua functions, each with how it is called, which the Lua editor offers as a name is typed."
)


def die(message):
    sys.exit(f"sync-mudlet-games: {message}")


def strip_comments(src):
    """The source without // and /* */ comments outside string literals."""
    out, i, in_string = [], 0, False
    while i < len(src):
        c = src[i]
        if in_string:
            out.append(c)
            if c == "\\":
                out.append(src[i + 1 : i + 2])
                i += 1
            elif c == '"':
                in_string = False
        elif c == '"':
            in_string = True
            out.append(c)
        elif src.startswith("//", i):
            while i < len(src) and src[i] != "\n":
                i += 1
            out.append("\n")
        elif src.startswith("/*", i):
            end = src.find("*/", i + 2)
            i = len(src) if end < 0 else end + 1
        else:
            out.append(c)
        i += 1
    return "".join(out)


def scan(body):
    """Each character of body with its brace and parenthesis depth, outside string literals (None inside one)."""
    depth, in_string, escaped = 0, False, False
    for i, c in enumerate(body):
        if in_string:
            if escaped:
                escaped = False
            elif c == "\\":
                escaped = True
            elif c == '"':
                in_string = False
            yield i, c, None
            continue
        if c == '"':
            in_string = True
            yield i, c, None
            continue
        if c in "{(":
            depth += 1
        yield i, c, depth
        if c in "})":
            depth -= 1


def top_level_groups(body):
    """The contents of each top-level { } group in body."""
    groups, start = [], None
    for i, c, depth in scan(body):
        if depth == 1 and c == "{":
            start = i + 1
        elif depth == 1 and c == "}" and start is not None:
            groups.append(body[start:i])
            start = None
    return groups


def split_top_level(body):
    """body split at the commas outside any braces, parentheses or string literal."""
    parts, start = [], 0
    for i, c, depth in scan(body):
        if depth == 0 and c == ",":
            parts.append(body[start:i])
            start = i + 1
    parts.append(body[start:])
    return [p.strip() for p in parts if p.strip()]


def string_value(expr):
    """The concatenated "..." literals of a C++ expression; QString() and no literal are the empty string."""
    escapes = {"n": "\n", "t": "\t", '"': '"', "\\": "\\", "'": "'"}
    out = []
    for literal in re.findall(r'"((?:[^"\\]|\\.)*)"', expr):
        out.append(re.sub(r"\\(.)", lambda m: escapes.get(m.group(1), m.group(1)), literal))
    return "".join(out)


def links_of(website_info, game):
    """The links of a game's websiteInfo: lines (split at <br>) each of an <a href>, a bare URL after its label, or a
    label for the link on the next line, as Accursed Lands' "Discord" is."""
    anchor = re.compile(r"""<a\s+href\s*=\s*(['"])(.*?)\1\s*>(.*?)</a>""", re.IGNORECASE | re.DOTALL)
    bare = re.compile(r"https?://\S+")
    links, label = [], ""
    for line in re.split(r"<br\s*/?>", website_info, flags=re.IGNORECASE):
        line = re.sub(r"\s+", " ", line).strip()
        found = [(m.group(3).strip(), m.group(2).strip()) for m in anchor.finditer(line)]
        rest = anchor.sub("", line).strip()
        if not found and (m := bare.search(rest)):
            found, rest = [(rest.replace(m.group(0), "").strip(" :"), m.group(0))], ""
        if "<" in rest or (found and rest):
            die(f"{game}: websiteInfo has a line the script cannot read ({line!r}); teach links_of() to read it")
        if not found:
            label = rest
            continue
        for text, url in found:
            if not re.match(r"https?://", url):
                die(f"{game}: a link the app cannot open: {url}")
            text = text or url
            links.append({"label": f"{label}: {text}" if label else text, "url": url})
            label = ""
    if label:
        die(f"{game}: websiteInfo ends with {label!r}, a label with no link")
    return links


def parse_games(header):
    clean = strip_comments(header)
    marker = clean.find("scmDefaultGames = {")
    if marker < 0:
        die("scmDefaultGames not found in TGameDetails.h: the header's shape changed")
    body = top_level_groups(clean[marker + len("scmDefaultGames = ") :])[0]
    games = []
    for group in top_level_groups(body):
        f = split_top_level(group)
        if len(f) < 7:
            die(f"an entry with {len(f)} fields, not 7 or more: {group[:80]!r}")
        # Desktop's dialog draws a game only as its logo, so one without (the self-test profile) is not shown there either
        if not string_value(f[5]):
            continue
        name = string_value(f[0])
        game = {
            "name": name,
            "host": string_value(f[1]),
            "port": int(f[2]),
            "tls": f[3] == "true",
            "links": links_of(string_value(f[4]), name),
            "description": string_value(f[6]).strip(),
            "icon": string_value(f[5]),
        }
        # After the seven, GameDetail's optional ownUi, which the engine reads itself, then alternateHostUrls
        for extra in f[7:]:
            if extra.startswith("{"):
                hosts = [string_value(h) for h in split_top_level(extra[1:-1])]
                game["alternateHosts"] = [h for h in hosts if h]
        games.append(game)
    if len(games) < 20:
        die(f"only {len(games)} games parsed: the header's shape changed")
    return games


def qrc_aliases(qrc):
    return {m.group(1): m.group(2).strip() for m in re.finditer(r'<file\s+alias="([^"]+)"\s*>([^<]+)</file>', qrc)}


class Source:
    """Mudlet's src/ at one commit: a checkout's, or GitHub's."""

    def __init__(self, checkout, commit):
        self.checkout = checkout
        self.commit = commit

    def read(self, path):
        if self.checkout:
            return (self.checkout / "src" / path).read_bytes()
        url = RAW.format(commit=self.commit, path=path)
        with urllib.request.urlopen(url, timeout=60) as response:
            return response.read()


def checkout_commit(checkout):
    try:
        commit = subprocess.run(["git", "-C", str(checkout), "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError) as e:
        die(f"{checkout} is not a git checkout of Mudlet: {e}")
    dirty = subprocess.run(["git", "-C", str(checkout), "status", "--porcelain", "--", "src/TGameDetails.h", "src/mudlet.qrc", "src/icons"],
                           capture_output=True, text=True, check=True).stdout
    if dirty:
        die(f"{checkout} has changes to the games' files that no commit holds:\n{dirty}")
    return commit


def catalogue(source):
    """games.json's content from source, and each game's logo as Mudlet has it, by the file name it gets here."""
    games = [g for g in parse_games(source.read("TGameDetails.h").decode("utf-8")) if g["name"] not in LEFT_OUT]
    aliases = qrc_aliases(source.read("mudlet.qrc").decode("utf-8"))
    logos = {}
    for game in games:
        key = re.sub(r"^(?::|qrc:)/+", "", game.pop("icon"))
        relative = aliases.get(key, key)
        data = source.read(relative)
        name = re.sub(r"[^a-z0-9]+", "_", Path(relative).stem.lower()).strip("_") + ".webp"
        if name in logos:
            die(f"two games' logos would both be {name}")
        logos[name] = data
        game["icon"] = name
        game["iconSource"] = relative
        game["iconSha256"] = hashlib.sha256(data).hexdigest()
    names = [g["name"].casefold() for g in games]
    if len(set(names)) != len(names):
        die("two games have the same name")
    return {"_comment": COMMENT, "mudletCommit": source.commit, "games": games}, logos


def lua_functions(source):
    return {"_comment": LUA_COMMENT, "mudletCommit": source.commit, "functions": json.loads(source.read("lua-function-list.json"))}


def encode(text_json):
    return json.dumps(text_json, indent=2, ensure_ascii=False) + "\n"


def scaled_webp(data):
    from PIL import Image  # noqa: PLC0415 - only writing needs Pillow

    image = Image.open(io.BytesIO(data))
    image = image.convert("RGBA" if image.mode in ("RGBA", "LA", "P") else "RGB")
    if image.mode == "RGBA" and image.getextrema()[3][0] == 255:
        image = image.convert("RGB")
    image.thumbnail(ICON_MAX, Image.Resampling.LANCZOS)
    out = io.BytesIO()
    image.save(out, "WEBP", quality=ICON_QUALITY, method=6)
    return out.getvalue()


def webp_size(data):
    """A WebP file's width and height, from its header, or None when it is not one."""
    if len(data) < 30 or data[:4] != b"RIFF" or data[8:12] != b"WEBP":
        return None
    chunk = data[12:16]
    if chunk == b"VP8X":
        return 1 + int.from_bytes(data[24:27], "little"), 1 + int.from_bytes(data[27:30], "little")
    if chunk == b"VP8 ":
        return int.from_bytes(data[26:28], "little") & 0x3FFF, int.from_bytes(data[28:30], "little") & 0x3FFF
    if chunk == b"VP8L":
        bits = int.from_bytes(data[21:25], "little")
        return 1 + (bits & 0x3FFF), 1 + ((bits >> 14) & 0x3FFF)
    return None


def write(checkout):
    source = Source(checkout, checkout_commit(checkout))
    content, logos = catalogue(source)
    ICON_DIR.mkdir(parents=True, exist_ok=True)
    for name, data in logos.items():
        (ICON_DIR / name).write_bytes(scaled_webp(data))
    for stale in ICON_DIR.iterdir():
        if stale.name not in logos:
            stale.unlink()
    OUT_JSON.write_text(encode(content), encoding="utf-8")
    functions = lua_functions(source)
    LUA_JSON.parent.mkdir(parents=True, exist_ok=True)
    LUA_JSON.write_text(encode(functions), encoding="utf-8")
    print(f"wrote {len(content['games'])} games and their logos, and {len(functions['functions'])} Lua functions, from Mudlet/Mudlet@{content['mudletCommit']}")


def check(checkout):
    text = OUT_JSON.read_text(encoding="utf-8")
    committed = json.loads(text)
    commit = committed.get("mudletCommit", "")
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        die(f"{OUT_JSON.relative_to(ROOT)} names no Mudlet commit")
    if checkout and checkout_commit(checkout) != commit:
        die(f"{checkout} is not at {commit}, the commit games.json is from")
    source = Source(checkout, commit)
    expected, logos = catalogue(source)
    problems = []
    lua_text = LUA_JSON.read_text(encoding="utf-8") if LUA_JSON.is_file() else ""
    if lua_text != encode(lua_functions(source)):
        problems.append(f"{LUA_JSON.relative_to(ROOT)} is not what the script writes from Mudlet at {commit[:9]}")
    if encode(committed) != text or committed != expected:
        problems.append(f"{OUT_JSON.relative_to(ROOT)} is not what the script writes from Mudlet at {commit[:9]}")
    present = {p.name for p in ICON_DIR.iterdir()} if ICON_DIR.is_dir() else set()
    for name in sorted(present ^ set(logos)):
        problems.append(f"icons/{name}: {'no game has it' if name in present else 'missing'}")
    for name in sorted(present & set(logos)):
        size = webp_size((ICON_DIR / name).read_bytes())
        if size is None or size[0] > ICON_MAX[0] or size[1] > ICON_MAX[1]:
            problems.append(f"icons/{name}: not a WebP of at most {ICON_MAX[0]} x {ICON_MAX[1]} ({size})")
    if problems:
        print("\n".join(problems), file=sys.stderr)
        die("rerun scripts/sync-mudlet-games.py with a Mudlet checkout at that commit, or at a newer one to take its list")
    print(f"games.json, its {len(logos)} logos and the Lua functions are Mudlet/Mudlet@{commit[:9]}'s")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("checkout", nargs="?", type=Path, help="a Mudlet/Mudlet checkout")
    parser.add_argument("--check", action="store_true", help="fail when the committed list is not what the script writes")
    args = parser.parse_args()
    if args.check:
        check(args.checkout)
    elif args.checkout:
        write(args.checkout)
    else:
        parser.error("give a Mudlet checkout to write from, or --check")


if __name__ == "__main__":
    main()
