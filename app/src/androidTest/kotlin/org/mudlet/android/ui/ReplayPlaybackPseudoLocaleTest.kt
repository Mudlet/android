/**
 * The replay bar and the game sheet's Play a replay (ReplayPlaybackTest) in the debug build's pseudo-locales, as
 * PseudoLocaleTest checks the screens: none of their text is cut short, the bar's at its longest, paused at 1024 times.
 */
@RunWith(Parameterized::class)
@SdkSuppress(minSdkVersion = Build.VERSION_CODES.TIRAMISU)
class ReplayPlaybackPseudoLocaleTest(private val locale: String) {
    private val fake = FakeEngineRule()
    private val compose = createAndroidComposeRule<MainActivity>()

    @get:Rule
    val rules: RuleChain = RuleChain.outerRule(MainThreadTimeout(TIMEOUT_MS)).around(fake)
        .around(GrantPermissionRule.grant(Manifest.permission.POST_NOTIFICATIONS))
        .around(AppLocaleRule(locale))
        .around(compose)

    private lateinit var session: FakeEngine.Session

    @Before
    fun openTheGameScreen() {
        compose.enableAccessibilityChecksOfWhatShows()
        session = fake.engine.nextSession()
        session.clear()
        session.synced(0)
        session.profiles(listOf(GAME), session.receive("listProfiles"))
        compose.waitUntil(WAIT_MS) { EngineClient.profiles == listOf(GAME) }
        activate(hasContentDescription(compose.activity.getString(R.string.profile_connect_to, GAME.name)))
        session.profiles(listOf(GAME), session.receive("openProfile"))
        session.status("profile", "${GAME.name} loaded")
        replay(playing = false)
        session.settings(emptyMap(), session.receive("getSettings").getLong("id"))
        compose.waitUntil(WAIT_MS) { compose.runOnIdle { EngineClient.front.settingsAvailable && !EngineClient.front.replay.playing } }
    }

    @Test
    fun theBarsTextFits() {
        replay(playing = true)
        val text = compose.activity.getString(R.string.replay_bar_paused, 1024)
        waitFor(hasText(text) and hasAnyAncestor(hasTestTag(REPLAY_BAR_TAG)))
        assertFits(text)
    }

    @Test
    fun thePlayButtonsTextFits() {
        activate(hasTestTag(GAME_TITLE_TAG))
        waitFor(hasTestTag(PLAY_REPLAY_TAG))
        compose.onNode(hasTestTag(PLAY_REPLAY_TAG)).performScrollTo()
        assertFits(compose.string(R.string.game_play_replay))
    }

    private fun assertFits(vararg texts: String) {
        compose.onRoot().tryPerformAccessibilityChecks()
        for (text in texts) {
            val layouts = ArrayList<TextLayoutResult>()
            compose.onNodeWithText(text, useUnmergedTree = true).fetchSemanticsNode().config.getOrNull(SemanticsActions.GetTextLayoutResult)?.action?.invoke(layouts)
            val layout = layouts.singleOrNull() ?: throw AssertionError("$locale: no layout for \"$text\"")
            assertFalse("$locale: \"$text\" is cut short", (0 until layout.lineCount).any { layout.isLineEllipsized(it) })
            assertFalse("$locale: \"$text\" has more lines than it may show", layout.multiParagraph.didExceedMaxLines)
        }
    }

    private fun replay(playing: Boolean) = session.send(JSONObject().put("t", "replay").put("playing", playing).put("paused", playing).put("speed", if (playing) 1024 else 0))

    private fun waitFor(matcher: SemanticsMatcher) = compose.waitUntil(WAIT_MS) { compose.onAllNodes(matcher, useUnmergedTree = true).fetchSemanticsNodes().isNotEmpty() }

    private fun activate(label: SemanticsMatcher) {
        compose.waitUntil(WAIT_MS) { compose.onAllNodes(label and hasClickAction()).fetchSemanticsNodes().isNotEmpty() }
        compose.onNode(label and hasClickAction()).performSemanticsAction(SemanticsActions.OnClick)
        compose.waitForIdle()
    }

    companion object {
        val GAME = Profile("Replay player", "127.0.0.1", 4000, false, "", false)
        const val WAIT_MS = 10_000L

        // Below the per-test timeout native/tests/android_instrumented.py gives the runner, so this one reports first
        const val TIMEOUT_MS = 240_000L

        @JvmStatic
        @Parameterized.Parameters(name = "{0}")
        fun locales() = listOf("en-XA", "ar-XB")
    }
}
